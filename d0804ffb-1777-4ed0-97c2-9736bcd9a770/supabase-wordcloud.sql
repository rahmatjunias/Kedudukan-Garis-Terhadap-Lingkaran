create table if not exists public.word_cloud_responses (
  id bigint generated by default as identity primary key,
  room_code text not null check (room_code ~ '^[a-z0-9-]{2,24}$'),
  answer text not null check (char_length(answer) between 2 and 40),
  created_at timestamptz not null default now()
);

create index if not exists word_cloud_responses_room_created_idx
  on public.word_cloud_responses (room_code, created_at desc);

alter table public.word_cloud_responses enable row level security;

grant select, insert on public.word_cloud_responses to anon;
grant usage, select on sequence public.word_cloud_responses_id_seq to anon;

create policy "Public can read word cloud responses"
  on public.word_cloud_responses
  for select
  to anon
  using (true);

create policy "Public can submit word cloud responses"
  on public.word_cloud_responses
  for insert
  to anon
  with check (
    room_code ~ '^[a-z0-9-]{2,24}$'
    and char_length(answer) between 2 and 40
  );
